#!/usr/bin/env python3
"""
Generates the `Provider` type of every mobile SDK from the committed provider list.

Source of truth: the backend's committed OpenAPI `Provider` enum (`clikgate_api/docs/openapi.json`,
`components.schemas.Provider.enum`: every gateway in `GET /v1/payment-gateways`, enabled or not, plus
`shopify`, `woocommerce` and `custom`). Its values are copied into `shared/providers.json`, which is
checked in, so builds and CI never call the API or a gateway.

    python3 scripts/generate_providers.py                       # rewrite the generated files from shared/providers.json
    python3 scripts/generate_providers.py --check               # fail if a generated file is out of date
    python3 scripts/generate_providers.py --openapi PATH        # refresh shared/providers.json from an openapi.json, then generate
    python3 scripts/generate_providers.py --check --openapi PATH  # also fail if the snapshot differs from that openapi.json

Without --openapi, --check also compares the snapshot with ../clikgate_api/docs/openapi.json when that
checkout exists next to this repository (skipped otherwise, e.g. in this repository's CI).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "shared" / "providers.json"
SIBLING_OPENAPI = ROOT.parent / "clikgate_api" / "docs" / "openapi.json"
KEY = re.compile(r"^[a-z][a-z0-9_]{1,29}$")

KOTLIN = ROOT / "android/clikgate/src/main/java/com/clikgate/Provider.kt"
SWIFT = ROOT / "ios/Sources/Clikgate/Public/ClikgateProvider.swift"
DART = ROOT / "flutter/lib/src/provider.dart"
TS = ROOT / "react-native/src/provider.ts"

HEADER = "Generated by scripts/generate_providers.py from shared/providers.json."


def camel(key: str, upper_first: bool) -> str:
    parts = key.split("_")
    head = parts[0].capitalize() if upper_first else parts[0]
    return head + "".join(p.capitalize() for p in parts[1:])


def kotlin(providers: list[str]) -> str:
    consts = "\n".join(
        f'        @JvmField public val {p.upper()}: Provider = Provider("{p}")' for p in providers
    )
    entries = ", ".join(p.upper() for p in providers)
    return f"""// {HEADER}
package com.clikgate

/**
 * A payment provider, for [Clikgate.goal]'s `provider`:
 * `Clikgate.goal("purchase", reference = "T123456", provider = Provider.PAYSTACK)`.
 *
 * The constants are the providers Clikgate knew when this SDK was released. For one added later,
 * use [fromString]; the server checks it.
 */
public class Provider private constructor(
    /** The wire value, such as `paystack`. */
    public val value: String,
) {{
    override fun equals(other: Any?): Boolean = other is Provider && other.value == value
    override fun hashCode(): Int = value.hashCode()
    override fun toString(): String = value

    public companion object {{
{consts}

        /** Every constant above, in Clikgate's order. */
        @JvmField public val entries: List<Provider> = listOf({entries})

        private val KEY = Regex("^[a-z][a-z0-9_]{{1,29}}$")

        /**
         * The provider for [value] (trimmed, lower-cased): a constant above when it is one, else a new
         * provider the server will check. Null when [value] isn't a provider key (`^[a-z][a-z0-9_]{{1,29}}$`).
         */
        @JvmStatic
        public fun fromString(value: String): Provider? {{
            val v = value.trim().lowercase(java.util.Locale.ROOT)
            if (!KEY.matches(v)) return null
            return entries.firstOrNull {{ it.value == v }} ?: Provider(v)
        }}
    }}
}}
"""


def swift(providers: list[str]) -> str:
    consts = "\n".join(
        f'    public static var {camel(p, False)}: ClikgateProvider {{ ClikgateProvider("{p}") }}' for p in providers
    )
    return f"""// {HEADER}
import Foundation

/// A payment provider, for `goal(_:provider:)`:
/// `Clikgate.shared.goal("purchase", reference: "T123456", provider: .paystack)`.
///
/// The constants are the providers Clikgate knew when this SDK was released. For one added later, use
/// `fromString(_:)`; the server checks it.
public struct ClikgateProvider: Hashable, Sendable {{
    /// The wire value, such as `paystack`.
    public let rawValue: String
    private init(_ v: String) {{ rawValue = v }}

    /// The provider for `value` (trimmed, lower-cased); nil when it isn't a provider key
    /// (`^[a-z][a-z0-9_]{{1,29}}$`). The server checks providers it doesn't know.
    public static func fromString(_ value: String) -> ClikgateProvider? {{
        let v = value.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        return v.range(of: "^[a-z][a-z0-9_]{{1,29}}$", options: .regularExpression) == nil ? nil : ClikgateProvider(v)
    }}

{consts}
}}
"""


def dart(providers: list[str]) -> str:
    consts = "\n".join(
        f"  static const {camel(p, False)} = ClikgateProvider._('{p}');" for p in providers
    )
    values = ", ".join(camel(p, False) for p in providers)
    return f"""// {HEADER}

/// A payment provider, for [Clikgate.goal]'s `provider`:
/// `Clikgate.goal('purchase', reference: 'T123456', provider: ClikgateProvider.paystack)`.
///
/// The constants are the providers Clikgate knew when this SDK was released.
/// For one added later, use [ClikgateProvider.fromString]; the server checks it.
class ClikgateProvider {{
  const ClikgateProvider._(this.value);

  /// The wire value, such as `paystack`.
  final String value;

{consts}

  /// Every constant above, in Clikgate's order.
  static const List<ClikgateProvider> values = [{values}];

  static final RegExp _key = RegExp(r'^[a-z][a-z0-9_]{{1,29}}$');

  /// The provider for [value] (trimmed, lower-cased): a constant above when it
  /// is one, else a new provider the server will check. Null when [value]
  /// isn't a provider key (`^[a-z][a-z0-9_]{{1,29}}$`).
  static ClikgateProvider? fromString(String value) {{
    final v = value.trim().toLowerCase();
    if (!_key.hasMatch(v)) return null;
    for (final p in values) {{
      if (p.value == v) return p;
    }}
    return ClikgateProvider._(v);
  }}

  @override
  bool operator ==(Object other) =>
      other is ClikgateProvider && other.value == value;

  @override
  int get hashCode => value.hashCode;

  @override
  String toString() => value;
}}
"""


def ts(providers: list[str]) -> str:
    consts = "\n".join(f"  {camel(p, True)}: '{p}'," for p in providers)
    return f"""// {HEADER}

/**
 * Payment providers Clikgate knew when this SDK was released, for `goal()`'s `provider`:
 * `Clikgate.goal('purchase', {{ reference: 'T123456', provider: ClikgateProvider.Paystack }})`.
 */
export const ClikgateProvider = {{
{consts}
}} as const;

/**
 * A payment provider: one of `ClikgateProvider`'s values, or a provider added after this SDK was
 * released (from `providerFromString`; the server checks it).
 */
export type ClikgateProvider =
  | (typeof ClikgateProvider)[keyof typeof ClikgateProvider]
  | (string & {{ readonly __clikgateProvider?: never }});

/** Every provider constant, in Clikgate's order. */
export const CLIKGATE_PROVIDERS: readonly ClikgateProvider[] = Object.freeze(
  Object.values(ClikgateProvider)
);

const PROVIDER_KEY = /^[a-z][a-z0-9_]{{1,29}}$/;

/**
 * The provider for `value` (trimmed, lower-cased), including providers added after this SDK was
 * released (the server checks them). `null` when `value` isn't a provider key
 * (`^[a-z][a-z0-9_]{{1,29}}$`).
 */
export function providerFromString(value: string): ClikgateProvider | null {{
  const v = String(value).trim().toLowerCase();
  return PROVIDER_KEY.test(v) ? v : null;
}}
"""


TARGETS = {KOTLIN: kotlin, SWIFT: swift, DART: dart, TS: ts}


def load_openapi(path: Path) -> list[str]:
    spec = json.loads(path.read_text())
    values = spec["components"]["schemas"]["Provider"]["enum"]
    return [str(v) for v in values]


def validate(providers: list[str]) -> None:
    bad = [p for p in providers if not KEY.match(p)]
    if bad:
        sys.exit(f"error: not provider keys: {bad}")
    if len(set(providers)) != len(providers):
        sys.exit("error: duplicate providers")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if anything is out of date; write nothing")
    ap.add_argument("--openapi", type=Path, help="the backend's committed openapi.json")
    args = ap.parse_args()

    snapshot = json.loads(SNAPSHOT.read_text()) if SNAPSHOT.exists() else None
    problems: list[str] = []

    openapi = args.openapi or (SIBLING_OPENAPI if args.check and SIBLING_OPENAPI.exists() else None)
    if openapi is not None:
        upstream = load_openapi(openapi)
        validate(upstream)
        if snapshot is None or snapshot.get("providers") != upstream:
            if args.check:
                problems.append(f"shared/providers.json differs from {openapi} (Provider enum)")
            else:
                snapshot = {
                    "source": "clikgate_api docs/openapi.json, components.schemas.Provider.enum",
                    "providers": upstream,
                }
                SNAPSHOT.write_text(json.dumps(snapshot, indent=2) + "\n")
                print(f"updated {SNAPSHOT.relative_to(ROOT)} ({len(upstream)} providers)")
        elif args.check:
            print(f"snapshot matches {openapi}")
    if snapshot is None:
        sys.exit("error: shared/providers.json is missing; run with --openapi PATH")

    providers = snapshot["providers"]
    validate(providers)
    for path, render in TARGETS.items():
        text = render(providers)
        rel = path.relative_to(ROOT)
        if args.check:
            if not path.exists() or path.read_text() != text:
                problems.append(f"{rel} is out of date")
        elif not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {rel}")

    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        print("Run: python3 scripts/generate_providers.py [--openapi ../clikgate_api/docs/openapi.json]", file=sys.stderr)
        return 1
    if args.check:
        print(f"providers up to date ({len(providers)} providers, {len(TARGETS)} generated files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
