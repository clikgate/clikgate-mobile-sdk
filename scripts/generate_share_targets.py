#!/usr/bin/env python3
"""
Generates the share-helper tables of the Engage add-ons from shared/share_targets.json.

`share.link(...)` gives each app its own version of a link (a short ending that tells Clikgate where it was
shared) and records the share with POST /v1/share-events. The tables say which app gets which ending, and how
each platform names the apps (Android package names, iOS bundle IDs). They are internal: the docs never list
the endings ("adds a short ending so Clikgate knows where you shared it").

Sources of truth: the backend's `ShareApp` enum (clikgate_api docs/openapi.json) and its endings table
(clikgate_api src/attribution/utils/share_endings.py), copied into shared/share_targets.json, which is checked in.

    python3 scripts/generate_share_targets.py           # rewrite the generated files
    python3 scripts/generate_share_targets.py --check   # fail if a generated file is out of date

--check also compares the snapshot with the backend checkout next to this repository when it exists
(skipped otherwise, e.g. in this repository's CI).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "shared" / "share_targets.json"
API = ROOT.parent / "clikgate_api"
SIBLING_OPENAPI = API / "docs" / "openapi.json"
SIBLING_ENDINGS = API / "src" / "attribution" / "utils" / "share_endings.py"

KOTLIN_APP = ROOT / "android/clikgate/src/main/java/com/clikgate/engage/ShareApp.kt"
SWIFT = ROOT / "ios/Sources/ClikgateEngage/EngageShareTargets.swift"
DART = ROOT / "flutter/lib/src/engage/share_app.dart"
TS = ROOT / "react-native/src/engage/shareApp.ts"

HEADER = "Generated by scripts/generate_share_targets.py from shared/share_targets.json."


def camel(key: str, upper_first: bool) -> str:
    parts = key.split("_")
    head = parts[0].capitalize() if upper_first else parts[0]
    return head + "".join(p.capitalize() for p in parts[1:])


def kotlin(t: dict) -> str:
    def entry(a: str) -> str:
        e = t["endings"].get(a)
        return f'    {a.upper()}("{a}", {f'"{e}"' if e else "null"})'
    entries = ",\n".join(entry(a) for a in t["share_apps"])
    return f"""// {HEADER}
package com.clikgate.engage

/**
 * The app a link was shared to ([EngageShare.link]'s `app`, and what Clikgate records for each share).
 * [OTHER] is any app Clikgate can't name. [value] is the wire value, such as `whatsapp`.
 */
public enum class ShareApp(public val value: String, internal val ending: String?) {{
{entries}
}}
"""


def kotlin_packages(t: dict) -> str:
    packages = ", ".join(f'"{p}"' for p, _ in t["android_packages"])
    apps = ", ".join(f"ShareApp.{a.upper()}" for _, a in t["android_packages"])
    return (
        "    // <generated:packages> (scripts/generate_share_targets.py; do not edit by hand)\n"
        "    /** Android packages Clikgate knows, in the order a direct share tries them, and their apps. */\n"
        f"    internal val PACKAGES: Array<String> = arrayOf({packages})\n"
        f"    internal val PACKAGE_APPS: Array<ShareApp> = arrayOf({apps})\n"
        "    // </generated:packages>"
    )


def with_block(path: Path, block: str) -> str:
    source = path.read_text()
    re_block = re.compile(r"^ {4}// <generated:packages>[^\n]*\n[\s\S]*?^ {4}// </generated:packages>$", re.MULTILINE)
    if not re_block.search(source):
        sys.exit(f"error: {path} has no <generated:packages> block")
    return re_block.sub(lambda _: block, source)


def swift(t: dict) -> str:
    cases = "\n".join(f'    case {camel(a, False)} = "{a}"' for a in t["share_apps"])
    endings = ", ".join(f'"{a}": "{e}"' for a, e in t["endings"].items())
    bundles = ", ".join(f'("{b.lower()}", "{a}")' for b, a in t["ios_bundle_ids"])
    return f"""// {HEADER}
import Foundation

/// The app a link was shared to (`share.link(...)`'s `app`, and what Clikgate records for each share).
/// `.other` is any app Clikgate can't name.
public enum ClikgateShareApp: String, Sendable {{
{cases}
}}

// Internal tables (never documented).
enum EngageShareTargets {{
    static let endings: [String: String] = [{endings}]
    /// App bundle IDs (lower-cased); a share extension's activity type starts with its app's bundle ID.
    static let bundles: [(String, String)] = [{bundles}]
}}
"""


def dart(t: dict) -> str:
    cases = "\n".join(f"  {camel(a, False)}('{a}')," for a in t["share_apps"])
    return f"""// {HEADER}

/// The app a link was shared to (`share.link`'s `app`, and what Clikgate
/// records for each share). [ShareApp.other] is any app Clikgate can't name.
enum ShareApp {{
{cases[:-1]};

  const ShareApp(this.value);

  /// The wire value, such as `whatsapp`.
  final String value;

  /// The app for [value] (trimmed, lower-cased), or null.
  static ShareApp? fromString(String value) {{
    final v = value.trim().toLowerCase();
    for (final a in values) {{
      if (a.value == v) return a;
    }}
    return null;
  }}
}}
"""


TS_NAMES = {"whatsapp": "WhatsApp", "tiktok": "TikTok", "linkedin": "LinkedIn", "youtube": "YouTube", "imessage": "IMessage"}


def ts(t: dict) -> str:
    consts = "\n".join(f"  {TS_NAMES.get(a, camel(a, True))}: '{a}'," for a in t["share_apps"])
    return f"""// {HEADER}

/**
 * The app a link was shared to (`share.link()`'s `app`, and what Clikgate records for each share).
 * `ShareApp.Other` is any app Clikgate can't name.
 */
export const ShareApp = {{
{consts}
}} as const;

export type ShareApp = (typeof ShareApp)[keyof typeof ShareApp];

/** Every share app, in Clikgate's order. */
export const SHARE_APPS: readonly ShareApp[] = Object.freeze(
  Object.values(ShareApp)
);
"""


KOTLIN_SHARE = ROOT / "android/clikgate/src/main/java/com/clikgate/engage/EngageShare.kt"
TARGETS = {
    KOTLIN_APP: kotlin,
    KOTLIN_SHARE: lambda t: with_block(KOTLIN_SHARE, kotlin_packages(t)),
    SWIFT: swift,
    DART: dart,
    TS: ts,
}


def backend_endings(path: Path) -> dict[str, str]:
    """`"w": MadeFor.WHATSAPP,` lines of share_endings.py -> {app: letter} (QR is not a share target)."""
    found = re.findall(r'^\s*"([a-z])": MadeFor\.([A-Z_]+),', path.read_text(), re.MULTILINE)
    return {app.lower(): letter for letter, app in found if letter != "q"}


def validate(t: dict) -> None:
    apps = t["share_apps"]
    if len(set(apps)) != len(apps) or not all(re.fullmatch(r"[a-z][a-z0-9_]*", a) for a in apps):
        sys.exit("error: share_apps must be unique lower_snake_case keys")
    for app, letter in t["endings"].items():
        if app not in apps or not re.fullmatch(r"[a-z]", letter):
            sys.exit(f"error: bad ending {app}: {letter}")
    for _, app in t["android_packages"] + t["ios_bundle_ids"]:
        if app not in apps:
            sys.exit(f"error: unknown app {app}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if anything is out of date; write nothing")
    args = ap.parse_args()
    t = json.loads(SNAPSHOT.read_text())
    validate(t)
    problems: list[str] = []
    if args.check and SIBLING_OPENAPI.exists():
        upstream = json.loads(SIBLING_OPENAPI.read_text())["components"]["schemas"]["ShareApp"]["enum"]
        if upstream != t["share_apps"]:
            problems.append(f"shared/share_targets.json share_apps differ from {SIBLING_OPENAPI} (ShareApp)")
    if args.check and SIBLING_ENDINGS.exists() and backend_endings(SIBLING_ENDINGS) != t["endings"]:
        problems.append(f"shared/share_targets.json endings differ from {SIBLING_ENDINGS}")
    for path, render in TARGETS.items():
        text = render(t)
        rel = path.relative_to(ROOT)
        if args.check:
            if not path.exists() or path.read_text() != text:
                problems.append(f"{rel} is out of date")
        elif not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {rel}")
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        print("Run: python3 scripts/generate_share_targets.py", file=sys.stderr)
        return 1
    if args.check:
        print(f"share targets up to date ({len(t['share_apps'])} apps, {len(TARGETS)} generated files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
